// The Distributed Mandelbrot's guest programs: BeebAsm sources in
// Examples/distributed-mandelbrot, assembled into MandelbrotGuest.swift
// (which the demo network puts on its file server). With beebasm about,
// they're assembled again here and must match; MACBEEB_WRITE_MANDELBROT=1
// writes MandelbrotGuest.swift afresh.

import Foundation
import Testing
@testable import BeebCore
import BeebHost
import BeebNetwork

struct MandelbrotGuestTests {
    static let beebasm = BeebAsm.locate(ProcessInfo.processInfo.environment["MACBEEB_BEEBASM"])
    static let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
        .deletingLastPathComponent()
    static let sources = ["worker", "cluster", "cluster2", "workers", "stopwk", "mandel", "mandel2"]

    /// Assembles the sources: each program's name, addresses and bytes.
    static func assemble() throws -> [MandelbrotGuest.File] {
        try sources.flatMap { source -> [MandelbrotGuest.File] in
            let path = root.appendingPathComponent("Examples/distributed-mandelbrot/\(source).asm").path
            let build = try BeebAsm.assemble(source: path, beebasm: beebasm)
            let volume = try DiscVolume(disc: Disc.fromImage(build.disc, format: .ssd))
            return try volume.items(at: .init()).map { item in
                MandelbrotGuest.File(name: item.name, loadAddress: item.loadAddress & 0xFFFF,
                                     executionAddress: item.executionAddress & 0xFFFF,
                                     contents: volume.contents(of: item, at: .init()))
            }
        }
    }

    @Test(.enabled(if: beebasm != nil))
    func builtFromTheSources() throws {
        let files = try Self.assemble()
        if ProcessInfo.processInfo.environment["MACBEEB_WRITE_MANDELBROT"] != nil {
            var text = """
            // Generated by MandelbrotGuestTests from Examples/distributed-mandelbrot
            // (MACBEEB_WRITE_MANDELBROT=1 make test): the Distributed Mandelbrot's
            // guest programs, as BeebAsm assembled them. Don't edit.

            extension MandelbrotGuest {
                public static let files: [File] = [

            """
            for file in files {
                text += "        File(name: \"\(file.name)\", loadAddress: 0x\(String(file.loadAddress, radix: 16, uppercase: true)), "
                    + "executionAddress: 0x\(String(file.executionAddress, radix: 16, uppercase: true)),\n"
                    + "             base64: \"\(Data(file.contents).base64EncodedString())\"),\n"
            }
            text += "    ]\n}\n"
            try text.write(to: Self.root.appendingPathComponent("Sources/BeebNetwork/MandelbrotGuestFiles.swift"), atomically: true, encoding: .utf8)
        }
        #expect(files.map(\.name) == MandelbrotGuest.files.map(\.name))
        for (built, embedded) in zip(files, MandelbrotGuest.files) {
            #expect(built == embedded, "\(built.name) differs: MACBEEB_WRITE_MANDELBROT=1 make test")
        }
    }
}
