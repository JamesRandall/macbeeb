// Emits BeebCore/CPU/M6502+Generated.swift.

/// Generates the Swift source for the CPU's state machine and opcode tables.
public func generateSwift() -> String {
    var e = Emitter()
    e.emitFile()
    return e.out
}

private struct Emitter {
    var out = ""
    private var indent = 0

    mutating func line(_ s: String = "") {
        if s.isEmpty {
            out += "\n"
        } else {
            out += String(repeating: "    ", count: indent) + s + "\n"
        }
    }

    mutating func block(_ header: String, _ body: (inout Emitter) -> Void) {
        line(header + " {")
        indent += 1
        body(&self)
        indent -= 1
        line("}")
    }

    mutating func emitFile() {
        let sequences = allSequences()
        let configs = allConfigs()

        line("// Generated by m6502-gen from M6502GenKit. Do not edit.")
        line("//")
        line("// Derived from b2's 6502_gen.cpp (Copyright (C) Tom Seddon, GPLv3).")
        line()
        line("// swiftlint:disable all")
        line()
        block("extension M6502") { e in
            e.emitStateEnum(sequences)
            e.line()
            e.emitOpEnum(configs)
            e.line()
            e.emitTick(sequences)
            e.line()
            for config in configs {
                e.emitOpcodeTable(config)
                e.line()
            }
        }
        line()
        block("extension M6502InstructionInfo") { e in
            for (index, config) in configs.enumerated() {
                if index > 0 { e.line() }
                e.emitInstructionInfo(config)
            }
        }
    }

    // MARK: States

    mutating func emitStateEnum(_ sequences: [BusSequence]) {
        block("enum State: UInt16") { e in
            e.line("case decode")
            for seq in sequences {
                e.line("// \(seq.description)")
                let names = (0...seq.cycles.count).map { "\(seq.stem)_\($0)" }
                e.line("case " + names.joined(separator: ", "))
            }
            e.line("// Hand-written (M6502+Special.swift)")
            for chunk in stride(from: 0, to: handwrittenStates.count, by: 6) {
                let names = handwrittenStates[chunk..<min(chunk + 6, handwrittenStates.count)]
                e.line("case " + names.joined(separator: ", "))
            }
        }
    }

    // MARK: Ops

    mutating func emitOpEnum(_ configs: [Config]) {
        var ops = Set<String>()
        for config in configs {
            for instr in config.instructions.values {
                if let op = instr.t0AndOp().op { ops.insert(op) }
            }
        }
        block("enum Op: UInt8") { e in
            e.line("case none")
            let sorted = ops.sorted()
            for chunk in stride(from: 0, to: sorted.count, by: 10) {
                e.line("case " + sorted[chunk..<min(chunk + 10, sorted.count)].joined(separator: ", "))
            }
        }
    }

    // MARK: Tick

    mutating func emitTick(_ sequences: [BusSequence]) {
        line("/// Runs phase 2 of the current cycle, then phase 1 of the next: on")
        line("/// return, `abus` and `access` describe the next bus access. For a")
        line("/// write, `dbus` holds the value to write; for a read, the caller")
        line("/// must put the value read into `dbus` before calling `tick()` again.")
        block("public func tick()") { e in
            e.block("if state == .decode") { e in
                e.line("opcode = dbus")
                e.line("let entry = opcodes[Int(opcode)]")
                e.line("op = entry.op")
                e.line("state = entry.t0")
            }
            e.block("switch state") { e in
                for seq in sequences {
                    e.emitSequenceCases(seq)
                }
                e.line("default:")
                e.indent += 1
                e.line("tickSpecial()")
                e.indent -= 1
            }
        }
    }

    mutating func emitSequenceCases(_ seq: BusSequence) {
        let n = seq.cycles.count
        for i in 0...n {
            line("case .\(seq.stem)_\(i):")
            indent += 1
            if i > 0 {
                emitAction(seq.cycles[i - 1], seq)
            }
            if i == n {
                line("nextInstruction()")
            } else {
                emitAccess(seq.cycles[i], seq)
                line("state = .\(seq.stem)_\(i + 1)")
                if i == n - 1 {
                    line("checkForInterrupts()")
                }
            }
            indent -= 1
        }
    }

    /// Phase 2: consume the data bus, then perform the cycle's action.
    mutating func emitAction(_ c: Cycle, _ seq: BusSequence) {
        if c.kind != .write, let what = c.what {
            line(whatDest(what))
        }
        switch c.action {
        case nil:
            break
        case "call":
            line("execute(op)")
        case "maybeCall":
            // No carry in the address calculation: the read was the real one.
            block("if !acarry") { e in
                e.line("execute(op)")
                e.line("nextInstruction()")
                e.line("return")
            }
        case "callBCDCMOS":
            line("execute(op)")
            block("if !d") { e in
                e.line("nextInstruction()")
                e.line("return")
            }
        case "jmp":
            line("pc = ad")
        default:
            preconditionFailure("unknown action \(c.action!)")
        }
    }

    /// Phase 1: put the address on the bus and set up the access.
    mutating func emitAccess(_ c: Cycle, _ seq: BusSequence) {
        for code in addressCode(c.addr, seq.index) {
            line(code)
        }
        if c.kind == .write {
            line(whatSource(c.what!))
        }
        switch c.kind {
        case .write: line("access = .write")
        case .readData: line("access = .data")
        case .readDataNoCarry: line("access = acarry ? .dummy : .data")
        case .readInstruction: line("access = .instruction")
        case .readAddress: line("access = .address")
        case .readDummy: line("access = .dummy")
        }
        switch c.action {
        case "maybeCall":
            // Penultimate cycle if no carry.
            block("if !acarry") { $0.line("checkForInterrupts()") }
        case "callBCDCMOS":
            block("if !d") { $0.line("checkForInterrupts()") }
        default:
            break
        }
    }

    func addressCode(_ addr: String, _ index: String?) -> [String] {
        let idx = index ?? "<no index>"
        switch addr {
        case "pc": return ["abus = pc"]
        case "pc++": return ["abus = pc", "pc &+= 1"]
        case "adl": return ["abus = ad & 0xFF"]
        case "ad": return ["abus = ad"]
        case "ial": return ["abus = ia & 0xFF"]
        case "ial+1": return ["abus = (ia &+ 1) & 0xFF"]
        case "sp": return ["abus = 0x100 | UInt16(s)"]
        case "ia": return ["abus = ia"]
        case "ia+1": return ["abus = ia &+ 1"]
        case "ial+x": return ["abus = (ia &+ UInt16(x)) & 0xFF"]
        case "ial+x+1": return ["abus = (ia &+ UInt16(x) &+ 1) & 0xFF"]
        case "resl": return ["abus = 0xFFFC"]
        case "resh": return ["abus = 0xFFFD"]
        case "1.ad+index":
            precondition(index != nil)
            return ["let t = (ad & 0xFF) &+ UInt16(\(idx))", "acarry = t > 0xFF", "abus = (ad & 0xFF00) | (t & 0xFF)"]
        case "2.ad+index":
            precondition(index != nil)
            return ["abus = ad &+ UInt16(\(idx))"]
        case "1.ia+x_cmos", "2.ia+x_cmos":
            return ["abus = ia &+ UInt16(x)"]
        case "3.ia+x_cmos":
            return ["abus = ia &+ UInt16(x) &+ 1"]
        case "sp++": return ["abus = 0x100 | UInt16(s)", "s &+= 1"]
        case "sp--": return ["abus = 0x100 | UInt16(s)", "s &-= 1"]
        case "adl+index":
            precondition(index != nil)
            return ["abus = (ad &+ UInt16(\(idx))) & 0xFF"]
        case "ia+1(nocarry)":
            // The high byte isn't fixed up: JMP ($xxFF) reads $xx00.
            return ["abus = (ia & 0xFF00) | ((ia &+ 1) & 0xFF)"]
        case "pba":
            return ["// address bus unchanged"]
        default:
            preconditionFailure("unknown address \(addr)")
        }
    }

    func whatDest(_ what: String) -> String {
        switch what {
        case "adl": return "ad = (ad & 0xFF00) | UInt16(dbus)"
        case "adh": return "ad = (ad & 0x00FF) | UInt16(dbus) << 8"
        case "data", "data!": return "data = dbus"
        case "ial": return "ia = (ia & 0xFF00) | UInt16(dbus)"
        case "iah": return "ia = (ia & 0x00FF) | UInt16(dbus) << 8"
        case "pcl": return "pc = (pc & 0xFF00) | UInt16(dbus)"
        case "pch": return "pc = (pc & 0x00FF) | UInt16(dbus) << 8"
        case "p": return "setP(dbus)"
        default: preconditionFailure("unknown what \(what)")
        }
    }

    func whatSource(_ what: String) -> String {
        switch what {
        case "data", "data!": return "dbus = data"
        case "pcl": return "dbus = UInt8(truncatingIfNeeded: pc)"
        case "pch": return "dbus = UInt8(truncatingIfNeeded: pc >> 8)"
        case "p": return "dbus = p"
        default: preconditionFailure("unknown what \(what)")
        }
    }

    // MARK: Tables

    mutating func emitOpcodeTable(_ config: Config) {
        line("static let \(config.name)Opcodes: [OpcodeEntry] = [")
        indent += 1
        for opcode in 0...255 {
            let instr = config.instructions[UInt8(opcode)]!
            let (t0, op) = instr.t0AndOp()
            line("OpcodeEntry(t0: .\(t0), op: .\(op ?? "none")), // \(hex(opcode)) \(instr.disassemblyMnemonic) \(instr.mode.rawValue)")
        }
        indent -= 1
        line("]")
    }

    mutating func emitInstructionInfo(_ config: Config) {
        line("public static let \(config.name): [M6502InstructionInfo] = [")
        indent += 1
        for opcode in 0...255 {
            let instr = config.instructions[UInt8(opcode)]!
            let mode = instr.mode.disassemblyMode
            let mnemonic = instr.mnemonic == "hlt" ? "hlt" : instr.disassemblyMnemonic
            line("M6502InstructionInfo(mnemonic: \"\(mnemonic)\", mode: .\(mode.rawValue), length: \(instr.mode.numBytes), undocumented: \(instr.undocumented)), // \(hex(opcode))")
        }
        indent -= 1
        line("]")
    }

    func hex(_ v: Int) -> String {
        let s = String(v, radix: 16, uppercase: true)
        return "$" + (s.count < 2 ? "0" + s : s)
    }
}
